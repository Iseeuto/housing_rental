import express from "express";

import {
  getUsers,
  getUserByID,
  addUser,
  updateUser,
  deleteUser,
  getUserBookings,
  getUserHousings,
} from "../controllers/users.controller.js";

import {
  validateUserFields,
  validateUserId,
  checkUserExists,
} from "../middleware/users.middleware.js";

const router = express.Router();

/**
 * @swagger
 * /users:
 *   get:
 *     summary: Get all users
 *     tags: [Users]
 *     responses:
 *       200:
 *         description: List of users
 */
router.get("/", getUsers);

/**
 * @swagger
 * /users/{id}:
 *   get:
 *     summary: Get user by ID
 *     tags: [Users]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *         schema:
 *           type: string
 *     responses:
 *       200:
 *         description: User found
 *       404:
 *         description: User not found
 */
router.get("/:id", validateUserId, checkUserExists, getUserByID);

/**
 * @swagger
 * /users/{id}/bookings:
 *   get:
 *     summary: Get bookings of a user
 *     tags: [Users]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *     responses:
 *       200:
 *         description: List of bookings
 */
router.get("/:id/bookings", validateUserId, checkUserExists, getUserBookings);

/**
 * @swagger
 * /users/{id}/housings:
 *   get:
 *     summary: Get housings of a user (landlord)
 *     tags: [Users]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *     responses:
 *       200:
 *         description: List of housings
 */
router.get("/:id/housings", validateUserId, checkUserExists, getUserHousings);

/**
 * @swagger
 * /users:
 *   post:
 *     summary: Create a user
 *     tags: [Users]
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required: [name, lastName, email, phone]
 *             properties:
 *               name:
 *                 type: string
 *               lastName:
 *                 type: string
 *               email:
 *                 type: string
 *               phone:
 *                 type: string
 *     responses:
 *       201:
 *         description: User created
 */
router.post("/", validateUserFields, addUser);

/**
 * @swagger
 * /users/{id}:
 *   put:
 *     summary: Update a user
 *     tags: [Users]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *     requestBody:
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             properties:
 *               name:
 *                 type: string
 *               lastName:
 *                 type: string
 *               email:
 *                 type: string
 *               phone:
 *                 type: string
 *     responses:
 *       200:
 *         description: User updated
 */
router.put(
  "/:id",
  validateUserId,
  checkUserExists,
  validateUserFields,
  updateUser,
);

/**
 * @swagger
 * /users/{id}:
 *   delete:
 *     summary: Delete a user
 *     tags: [Users]
 *     parameters:
 *       - in: path
 *         name: id
 *         required: true
 *     responses:
 *       200:
 *         description: User deleted
 */
router.delete("/:id", validateUserId, checkUserExists, deleteUser);

export default router;
